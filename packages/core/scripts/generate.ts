// Generates src/generated/ from the JSON Schemas in kit/company/schemas: the schemas themselves, for
// runtime validation, and a TypeScript type for each schema and each of its $defs.
//
//   node packages/core/scripts/generate.ts           writes the files
//   node packages/core/scripts/generate.ts --check   fails when they're out of date

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { format, resolveConfig } from "prettier";

type Schema = boolean | Record<string, any>;

const ROOT = join(import.meta.dirname, "..", "..", "..");
const SCHEMA_DIR = join(ROOT, "kit", "company", "schemas");
const OUT_DIR = join(import.meta.dirname, "..", "src", "generated");
const HEADER =
    "// Generated by packages/core/scripts/generate.ts from kit/company/schemas. Don't edit.\n";

export function generate(): Record<string, string> {
    const schemas: Record<string, Record<string, any>> = {};
    for (const file of readdirSync(SCHEMA_DIR).sort()) {
        if (file.endsWith(".schema.json"))
            schemas[file] = JSON.parse(readFileSync(join(SCHEMA_DIR, file), "utf8"));
    }
    const types = Object.entries(schemas).flatMap(([file, schema]) => {
        const base = typeName(file);
        const defs = Object.entries((schema.$defs ?? {}) as Record<string, Schema>).map(
            ([name, def]) => `export type ${base}${pascal(name)} = ${toType(def, file, 0)};\n`,
        );
        const doc = schema.description
            ? `/** ${schema.description.replace(/\*\//g, "*\\/")} */\n`
            : "";
        return [`${doc}export type ${base} = ${toType(schema, file, 0)};\n`, ...defs];
    });
    return {
        "schemas.ts": `${HEADER}\nexport const SCHEMAS: Record<string, object> = ${JSON.stringify(schemas, null, 4)};\n`,
        "types.ts": `${HEADER}\n${types.join("\n")}`,
    };
}

function typeName(file: string): string {
    return pascal(file.replace(/\.schema\.json$/, ""));
}

function pascal(name: string): string {
    return name
        .split(/[^A-Za-z0-9]+/)
        .filter(Boolean)
        .map((part) => part[0].toUpperCase() + part.slice(1))
        .join("");
}

function refType(ref: string, file: string): string {
    const [target, pointer] = ref.split("#");
    const base = typeName(target || file);
    const def = pointer?.match(/^\/\$defs\/(.+)$/)?.[1];
    return def ? base + pascal(def) : base;
}

function indent(depth: number): string {
    return "    ".repeat(depth);
}

function literal(value: unknown): string {
    return JSON.stringify(value);
}

function isConditional(member: Schema): boolean {
    return typeof member === "object" && "if" in member;
}

// The property an if/then list switches on, when every member tests the same property with const
// or enum, as event.schema.json does with `type`.
function discriminator(members: Schema[]): string | undefined {
    if (!members.length || !members.every(isConditional)) return undefined;
    const keys = members.map((m) => {
        const props = (m as Record<string, any>).if?.properties ?? {};
        const names = Object.keys(props);
        return names.length === 1 && ("const" in props[names[0]] || "enum" in props[names[0]])
            ? names[0]
            : undefined;
    });
    return keys.every((k) => k && k === keys[0]) ? keys[0] : undefined;
}

function toType(schema: Schema, file: string, depth: number): string {
    if (schema === true) return "unknown";
    if (schema === false) return "never";
    if (schema.$ref) return refType(schema.$ref, file);
    if ("const" in schema) return literal(schema.const);
    if (schema.enum) return (schema.enum as unknown[]).map(literal).join(" | ");
    const union = schema.anyOf ?? schema.oneOf;
    if (union) {
        const own = { ...schema, anyOf: undefined, oneOf: undefined };
        const parts = (union as Schema[]).filter(hasShape).map((m) => toType(m, file, depth));
        const rest = hasShape(own) ? toType(own, file, depth) : undefined;
        if (!parts.length) return rest ?? "unknown";
        const joined = parts.length > 1 ? `(${parts.join(" | ")})` : parts[0];
        return rest ? `${rest} & ${joined}` : joined;
    }
    if (schema.allOf) {
        const members = schema.allOf as Schema[];
        const own = { ...schema, allOf: undefined };
        const key = discriminator(members);
        if (key) {
            const base = toType(own, file, depth);
            const variants = members.map((m) => {
                const { if: test, then } = m as Record<string, any>;
                const tag = test.properties[key];
                const tagType =
                    "const" in tag ? literal(tag.const) : tag.enum.map(literal).join(" | ");
                const body = toType({ type: "object", ...then }, file, depth);
                return `(Omit<${base}, ${literal(key)}> & { ${key}: ${tagType} } & ${body})`;
            });
            return variants.join(" | ");
        }
        const parts = members
            .filter((m) => !isConditional(m) && hasShape(m))
            .map((m) => toType(m, file, depth));
        const self = hasShape(own) ? [toType(own, file, depth)] : [];
        const all = [...self, ...parts];
        return all.length ? all.join(" & ") : "unknown";
    }
    const types = Array.isArray(schema.type) ? schema.type : schema.type ? [schema.type] : [];
    if (types.length > 1)
        return types.map((t: string) => toType({ ...schema, type: t }, file, depth)).join(" | ");
    const type = types[0] ?? (schema.properties ? "object" : schema.items ? "array" : undefined);
    switch (type) {
        case "string":
            return "string";
        case "integer":
        case "number":
            return "number";
        case "boolean":
            return "boolean";
        case "null":
            return "null";
        case "array":
            return schema.items ? `${wrap(toType(schema.items, file, depth))}[]` : "unknown[]";
        case "object":
            return objectType(schema, file, depth);
        default:
            return "unknown";
    }
}

function hasShape(schema: Schema): boolean {
    if (typeof schema === "boolean") return true;
    return ["$ref", "const", "enum", "anyOf", "oneOf", "allOf", "type", "properties", "items"].some(
        (k) => schema[k] !== undefined,
    );
}

function wrap(type: string): string {
    return /[|&]/.test(type) ? `(${type})` : type;
}

function objectType(schema: Record<string, any>, file: string, depth: number): string {
    const required = new Set<string>(schema.required ?? []);
    const props = Object.entries((schema.properties ?? {}) as Record<string, Schema>);
    const extra = schema.additionalProperties;
    const lines = props.map(([name, prop]) => {
        const key = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : literal(name);
        return `${indent(depth + 1)}${key}${required.has(name) ? "" : "?"}: ${toType(prop, file, depth + 1)};`;
    });
    for (const name of required) {
        if (!(schema.properties ?? {})[name]) lines.push(`${indent(depth + 1)}${name}: unknown;`);
    }
    if (extra && typeof extra === "object") {
        const value = toType(extra, file, depth + 1);
        if (!props.length) return `Record<string, ${value}>`;
        lines.push(`${indent(depth + 1)}[key: string]: ${value} | undefined;`);
    } else if (!lines.length) {
        return "Record<string, unknown>";
    }
    return `{\n${lines.join("\n")}\n${indent(depth)}}`;
}

if (import.meta.main) {
    const check = process.argv.includes("--check");
    let stale = false;
    for (const [name, raw] of Object.entries(generate())) {
        const path = join(OUT_DIR, name);
        const content = await format(raw, { ...(await resolveConfig(path)), filepath: path });
        let current = "";
        try {
            current = readFileSync(path, "utf8");
        } catch {}
        if (current === content) continue;
        if (check) {
            console.error(`${path} is out of date. Run pnpm sdk:generate.`);
            stale = true;
        } else writeFileSync(path, content);
    }
    if (stale) process.exit(1);
}
